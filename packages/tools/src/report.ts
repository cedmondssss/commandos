import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { basename, dirname, extname, join } from 'node:path';
import { JsonValueSchema } from '@commandos/contracts';
import { z } from 'zod';
import { ensureDir, PathArg, pathExists, sha256File } from './fs';
import { displayPath, resolveUserPath, uniquePath } from './paths';
import { defineTool } from './types';

function cell(v: unknown): string {
  if (v === null || v === undefined) return '';
  if (typeof v === 'string') return v.startsWith('/') ? displayPath(v) : v;
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return JSON.stringify(v);
}

function mdEscape(s: string): string {
  return s.replace(/\|/g, '\\|').replace(/\r?\n/g, ' ');
}

function htmlEscape(s: string): string {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

export function pickColumns(entries: Array<Record<string, unknown>>, requested?: string[]): string[] {
  if (requested?.length) return requested;
  const seen = new Map<string, number>();
  for (const e of entries) for (const k of Object.keys(e)) seen.set(k, (seen.get(k) ?? 0) + 1);
  return [...seen.keys()].slice(0, 8);
}

export function renderMarkdown(title: string, intro: string | undefined, entries: Array<Record<string, unknown>>, columns: string[]): string {
  const lines = [`# ${title}`, '', `_Generated by CommandOS on ${new Date().toLocaleString()}_`, ''];
  if (intro) lines.push(intro, '');
  if (entries.length) {
    lines.push(`| ${columns.map(mdEscape).join(' | ')} |`, `| ${columns.map(() => '---').join(' | ')} |`);
    for (const e of entries) lines.push(`| ${columns.map((c) => mdEscape(cell(e[c]))).join(' | ')} |`);
    lines.push('', `${entries.length} item(s).`);
  }
  return `${lines.join('\n')}\n`;
}

export function renderHtml(title: string, intro: string | undefined, entries: Array<Record<string, unknown>>, columns: string[]): string {
  const rows = entries
    .map((e) => `<tr>${columns.map((c) => `<td>${htmlEscape(cell(e[c]))}</td>`).join('')}</tr>`)
    .join('\n');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>${htmlEscape(title)}</title>
<style>
:root{color-scheme:light dark;--bg:#fff;--fg:#1d1d1f;--muted:#6e6e73;--line:#e5e5ea;--head:#f5f5f7}
@media (prefers-color-scheme:dark){:root{--bg:#1c1c1e;--fg:#f5f5f7;--muted:#a1a1a6;--line:#38383a;--head:#2c2c2e}}
body{font:14px/1.5 -apple-system,BlinkMacSystemFont,"SF Pro Text",sans-serif;background:var(--bg);color:var(--fg);margin:32px auto;max-width:1100px;padding:0 16px}
h1{font-size:24px;margin:0 0 4px}.meta{color:var(--muted);margin:0 0 20px}
table{border-collapse:collapse;width:100%}th,td{border-bottom:1px solid var(--line);padding:8px 10px;text-align:left;vertical-align:top}
th{background:var(--head);font-weight:600}td{word-break:break-word}
</style></head><body>
<h1>${htmlEscape(title)}</h1>
<p class="meta">Generated by CommandOS on ${htmlEscape(new Date().toLocaleString())} · ${entries.length} item(s)</p>
${intro ? `<p>${htmlEscape(intro)}</p>` : ''}
${entries.length ? `<table><thead><tr>${columns.map((c) => `<th>${htmlEscape(c)}</th>`).join('')}</tr></thead><tbody>\n${rows}\n</tbody></table>` : ''}
</body></html>
`;
}

export const reportWrite = defineTool({
  id: 'report.write',
  undo: 'journaled',
  title: 'Write report',
  description:
    'Write a Markdown report (and an HTML version alongside it) with a title, optional intro and a table built from entries (array of objects, e.g. fs.organize output.moved). Never overwrites: picks a free file name. Reversible.',
  tier: 1,
  args: z.object({
    title: z.string().min(1).max(200),
    outputPath: PathArg.describe('Path of the .md file to create'),
    intro: z.string().max(10_000).optional(),
    entries: z.array(z.record(z.string(), JsonValueSchema)).max(10_000).default([]),
    columns: z.array(z.string().min(1).max(60)).max(12).optional(),
    html: z.boolean().default(true),
  }),
  output: z.object({ markdownPath: z.string(), htmlPath: z.string().nullable(), entryCount: z.number().int() }),
  effectClass: 'reversible_local',
  effects: ['fs_write'],
  risk: 'low',
  idempotent: false,
  defaultTimeoutMs: 15_000,
  paths: (a) => ({ read: [], write: [a.outputPath] }),
  itemCount: (a) => (a.html ? 2 : 1),
  resources: (a) => [`fs:${dirname(resolveUserPath(a.outputPath))}`],
  preview: (a) => ({ summary: `Write report “${a.title}” to ${displayPath(resolveUserPath(a.outputPath))}`, details: [] }),
  async run(a, ctx) {
    const requested = resolveUserPath(a.outputPath);
    const dir = dirname(requested);
    const created: string[] = [];
    await ensureDir(dir, ctx, created);
    const stem = basename(requested, extname(requested)) || 'report';
    const mdPath = await uniquePath(dir, `${stem}.md`);
    const entries = a.entries as Array<Record<string, unknown>>;
    const columns = pickColumns(entries, a.columns);
    await writeFile(mdPath, renderMarkdown(a.title, a.intro, entries, columns), { encoding: 'utf8', flag: 'wx' });
    await ctx.journal.record({ kind: 'delete_created', path: mdPath, isDir: false, sha256: await sha256File(mdPath) });
    let htmlPath: string | null = null;
    if (a.html) {
      htmlPath = await uniquePath(dir, `${basename(mdPath, '.md')}.html`);
      await mkdir(dirname(htmlPath), { recursive: true });
      await writeFile(htmlPath, renderHtml(a.title, a.intro, entries, columns), { encoding: 'utf8', flag: 'wx' });
      await ctx.journal.record({ kind: 'delete_created', path: htmlPath, isDir: false, sha256: await sha256File(htmlPath) });
    }
    return { markdownPath: mdPath, htmlPath, entryCount: entries.length };
  },
  async verify(a, o) {
    const md = await readFile(o.markdownPath, 'utf8').catch(() => '');
    const checks = [
      { label: `report written: ${displayPath(o.markdownPath)}`, ok: md.startsWith(`# ${a.title}`) },
      { label: `report lists ${o.entryCount} item(s)`, ok: o.entryCount === 0 || md.includes(`${o.entryCount} item(s).`) },
    ];
    if (o.htmlPath) checks.push({ label: `HTML written: ${displayPath(o.htmlPath)}`, ok: await pathExists(o.htmlPath) });
    return checks;
  },
});

export const reportTools = [reportWrite];

export function reportPathFor(dir: string, title: string): string {
  return join(dir, `${title.replace(/[^\p{L}\p{N} _-]/gu, '').trim() || 'Report'}.md`);
}
